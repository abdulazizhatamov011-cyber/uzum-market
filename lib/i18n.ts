const dicts: Record<Lang, Dict> = { uz, ru };
export const getDict = (lang: Lang) => dicts[lang];

// Sayt ichidagi manzilga til prefiksini qo'shadi: uz → /cart, ru → /ru/cart
export function localize(lang: Lang, path: string) {
  if (lang === "uz" || !path.startsWith("/") || path.startsWith("/ru")) return path;
  return path === "/" ? "/ru" : `/ru${path}`;
}

// Joriy manzildan til prefiksini olib tashlaydi: /ru/cart → /cart
export function stripLocale(path: string) {
  return path.replace(/^\/ru(?=\/|$)/, "") || "/";
}

// Toshkent vaqti (UTC+5) bo'yicha — server va brauzerda bir xil natija beradi
export function formatDateTime(iso: string, lang: Lang) {
  const d = new Date(Date.parse(iso) + 5 * 3600_000);
  const hh = String(d.getUTCHours()).padStart(2, "0");
  const mm = String(d.getUTCMinutes()).padStart(2, "0");
  const month = dicts[lang].months[d.getUTCMonth()];
  return lang === "ru"
    ? `${d.getUTCDate()} ${month} ${d.getUTCFullYear()}, ${hh}:${mm}`
    : `${d.getUTCDate()}-${month}, ${d.getUTCFullYear()}, ${hh}:${mm}`;
}
